#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.12"
# dependencies = ["pillow"]
# ///
"""Pack the edited frames in art/ into the sprite sheets the mod loads.

    uv run tools/pack-art.py

Reads art/<target>/manifest.json and the per-frame PNGs from extract-biter-art.py,
and writes graphics/entity/<target>/<anim>[-shadow]-N.png plus a matching .lua that
data.lua requires. graphics/ is generated output: everything this script owns in it
is deleted and rewritten on each run, so edit art/, never graphics/.

Factorio reads sprites once at startup, so restart the game after packing.
"""

import json
import math
import shutil
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "art"
GRAPHICS = ROOT / "graphics"

# Vanilla keeps every sheet file within 4096px a side; the same limit happens to
# reproduce vanilla's column counts for attack, die and decay.
MAX_SHEET = 4096


def check_frames(src: Path, meta: dict, frames: int, directions: list[str]) -> list[str]:
    """Cheap pass that reads only PNG headers, so a bad edit fails before anything is written."""
    size = (meta["width"], meta["height"])
    problems = []
    for dir_name in directions:
        for f in range(frames):
            path = src / dir_name / f"{f:02d}.png"
            if not path.exists():
                problems.append(f"missing {path.relative_to(ROOT)}")
                continue
            with Image.open(path) as img:
                if img.size != size:
                    # The frame's centre is its anchor in game, so a resized or cropped
                    # canvas would shift the sprite against its shadow and hitbox.
                    problems.append(f"{path.relative_to(ROOT)} is {img.size[0]}x{img.size[1]}, expected {size[0]}x{size[1]}")
    return problems


def pack(src: Path, meta: dict, frames: int, directions: list[str], out: Path, name: str) -> list[str]:
    w, h = meta["width"], meta["height"]
    columns = min(frames, MAX_SHEET // w)
    lines_per_file = MAX_SHEET // h
    per_file = columns * lines_per_file
    total = len(directions) * frames

    sheets = []
    for start in range(0, total, per_file):
        rows = math.ceil(min(per_file, total - start) / columns)
        sheets.append(Image.new("RGBA", (columns * w, rows * h)))

    warnings = []
    for d, dir_name in enumerate(directions):
        for f in range(frames):
            path = src / dir_name / f"{f:02d}.png"
            img = Image.open(path).convert("RGBA")
            # An editor that flattens or exports without alpha leaves a solid
            # rectangle that would be drawn around the bug in game.
            if img.getextrema()[3][0] == 255:
                warnings.append(f"{path.relative_to(ROOT)} has no transparent pixels")
            # Direction-major, filling rows left to right and spilling into the next
            # file: the same order as the vanilla sheets.
            file_index, local = divmod(d * frames + f, per_file)
            row, col = divmod(local, columns)
            sheets[file_index].paste(img, (col * w, row * h))

    suffixes = []
    for i, sheet in enumerate(sheets, start=1):
        suffixes.append(f"-{i}.png")
        sheet.save(out / f"{name}-{i}.png")

    sx, sy = meta["shift_by_pixel"]
    filenames = ", ".join(f'"{s}"' for s in suffixes)
    (out / f"{name}.lua").write_text(
        f"-- Generated by tools/pack-art.py from {src.relative_to(ROOT)}. Edit the frames, not this file.\n"
        "return\n"
        "{\n"
        f"  width = {w},\n"
        f"  height = {h},\n"
        f"  shift = {{{sx} / 32, {sy} / 32}},\n"
        f"  line_length = {columns},\n"
        f"  lines_per_file = {lines_per_file},\n"
        f"  frame_count = {frames},\n"
        f"  direction_count = {len(directions)},\n"
        f"  filenames = {{ {filenames} }},\n"
        "}\n"
    )
    return warnings


def jobs_for(target_dir: Path, manifest: dict, out: Path):
    """(src, meta, frames, directions, out, name) for every sheet a target packs into."""
    directions = manifest["directions"]
    for anim, spec in manifest["animations"].items():
        frames = spec["frames_per_direction"]
        yield target_dir / anim / "color", spec["color"], frames, directions, out, anim
        if "shadow" in spec:
            yield target_dir / anim / "shadow", spec["shadow"], frames, directions, out, f"{anim}-shadow"


def main():
    targets = sorted(p.parent for p in ART.glob("*/manifest.json"))
    if not targets:
        raise SystemExit("no art/<target>/manifest.json found; run tools/extract-biter-art.py first")

    plan = []
    problems = []
    for target_dir in targets:
        manifest = json.loads((target_dir / "manifest.json").read_text())
        out = GRAPHICS / "entity" / target_dir.name
        for src, meta, frames, directions, _, _ in jobs_for(target_dir, manifest, out):
            problems += check_frames(src, meta, frames, directions)
        plan.append((target_dir, manifest, out))

    if problems:
        print("\n".join(problems), file=sys.stderr)
        raise SystemExit(f"{len(problems)} problem(s); nothing was packed")

    icon_dir = GRAPHICS / "icons"
    icon_dir.mkdir(parents=True, exist_ok=True)
    with ProcessPoolExecutor() as pool:
        futures = []
        for target_dir, manifest, out in plan:
            shutil.rmtree(out, ignore_errors=True)
            out.mkdir(parents=True)
            for job in jobs_for(target_dir, manifest, out):
                futures.append(pool.submit(pack, *job))
            for role, suffix in (("icon", ""), ("corpse_icon", "-corpse")):
                shutil.copyfile(target_dir / manifest["icons"][role]["file"], icon_dir / f"{target_dir.name}{suffix}.png")
        warnings = [w for fut in futures for w in fut.result()]

    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    for target_dir, _, out in plan:
        print(f"{target_dir.name}: {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
